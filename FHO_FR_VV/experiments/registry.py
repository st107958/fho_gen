def get_experiment(m1: str, m2: str, p_torr: float) -> dict[str, Any]:
    """Возвращает параметры эксперимента для заданной пары частиц и давления.

    Raises
    ------
    KeyError
        Если эксперимент не найден в registry.
    """
    key = (m1, m2, p_torr)
    if key not in REGISTRY:
        available = ", ".join(f"({m},{b},{p})" for m, b, p in REGISTRY)
        raise KeyError(
            f"Эксперимент ({m1}, {m2}, {p_torr}) не найден. "
            f"Доступные: {available}"
        )
    return dict(REGISTRY[key])


def experiment_exists(m1: str, m2: str, p_torr: float) -> bool:
    """Проверяет, есть ли эксперимент в registry."""
    return (m1, m2, p_torr) in REGISTRY
